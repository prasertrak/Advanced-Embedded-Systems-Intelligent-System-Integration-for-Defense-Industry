void setPWM(int no,int pwm){
	if(pwm<0) pwm=0;
	if(pwm>99) pwm=99;
	if(no) // right servo
		TIM14->CCR1 = 500+pwm*5;
	else   // left servo
		TIM8->CCR4 = 500+pwm*5;
}
