/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  int i;
  int j,jj;
  int sData;
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_DAC_Init();
  MX_TIM6_Init();
  MX_TIM3_Init();
  MX_I2C1_Init();
  /* USER CODE BEGIN 2 */
  //Sine wave generation
  for(i=0;i<1000;i++)
    waveTable[i] = (uint32_t)(sin((float)i*2*PI/1000.0)*(1241.212121)+2048);
  HAL_DAC_Start_DMA(&hdac,DAC_CHANNEL_1,waveTable,1000,DAC_ALIGN_12B_R);
  HAL_TIM_Base_Start(&htim6);

  ssd1306_Init();
  HAL_ADC_Start_IT(&hadc1);
  HAL_TIM_Base_Start_IT(&htim3);
  changeTimValue(timePreScaler[timeNow],timePeriod[timeNow]);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    for(int i=0;i<4;i++){
    	if(isButtonPressed(i)){
    		switch(i){
    		case 0: //toggle time scale
    			if(timeNow>6){ timeNow=1; }else{ timeNow++;}
    			changeTimValue(timePreScaler[timeNow],timePeriod[timeNow]);
    			break;
    		case 1: // increase trigger voltage
    			if(trigValue<4000){trigValue+=64;} break;
    		case 2: // decrease trigger voltage
    			if(trigValue>0){trigValue-=64;}break;
    		case 3: // toggle trigger up/down
    			if(isTrigUp) isTrigUp=0; else isTrigUp=1; break;
    		}
    	}
    }
	if(isDataReady){
		if(dataOffset) sData=0; else sData=256; //Use another buffer
		isDataReady=0;
		ssd1306_Fill(Black);
		ssd1306_SetCursor(0,0);
		ssd1306_WriteString(time[timeNow],Font_6x8,White);
		ssd1306_SetCursor(120,(4095-trigValue)>>7);
		ssd1306_WriteString("<",Font_6x8,White);
		ssd1306_SetCursor(120,0);
		if(isTrigUp){
			ssd1306_WriteString("^",Font_6x8,White);
		}else{
			ssd1306_WriteString("v",Font_6x8,White);
		}
		for(j=0;j<255;j++){
			if(isTrigUp){
				if((data[j+sData]<trigValue)&&(data[j+sData+1]>=trigValue))break;
			}else{
				if((data[j+sData]>trigValue)&&(data[j+sData+1]<=trigValue))break;
			}
		}
		if(j==255){
			j=0;
			ssd1306_SetCursor(120,10);
			ssd1306_WriteString("X",Font_6x8,White);
		}
		for(jj=0;(jj<127)&&(j<255);jj++,j++){
			ssd1306_Line(jj,31-(data[j+sData]>>7),jj+1,31-(data[j+sData+1]>>7),White);
		}
		ssd1306_UpdateScreen();
	}
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

