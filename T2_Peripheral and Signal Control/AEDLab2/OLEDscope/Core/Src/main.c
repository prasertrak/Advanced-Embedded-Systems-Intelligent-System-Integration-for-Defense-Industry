void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc){
  if(hadc==&hadc1){
    data[i+dataOffset]=HAL_ADC_GetValue(hadc);
    i = (i+1)&0xff;
    if(!i){
    	HAL_GPIO_TogglePin(GPIOA,GPIO_PIN_5);
    	if(!isDataReady){
    	   if(!dataOffset) dataOffset=256;
    	   else dataOffset=0;
    	}
    	isDataReady=1;
    }
    HAL_ADC_Start_IT(hadc);
  }
}

int changeTimValue(uint16_t preScaler,uint16_t period){
	  htim3.Instance = TIM3;
	  htim3.Init.Prescaler = preScaler;
	  htim3.Init.CounterMode = TIM_COUNTERMODE_UP;
	  htim3.Init.Period = period;
	  htim3.Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
	  htim3.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_ENABLE;
	  if (HAL_TIM_Base_Init(&htim3) != HAL_OK)
	  {
	    Error_Handler();
	  }
	  return 1;
}

int isButtonPressed(int bt){
	int x1=HAL_GPIO_ReadPin(buttonPort[bt&3],button[bt&3]);
	HAL_Delay(50);  //Delay for a bit to check for debouncing
	int x2=HAL_GPIO_ReadPin(buttonPort[bt&3],button[bt&3]);
	if((x1==x2)&&(x2==0)){
		HAL_GPIO_WritePin(ledPort[bt],ledGPIO[bt],1);
		while(!HAL_GPIO_ReadPin(buttonPort[bt&3],button[bt&3])){
			HAL_Delay(10);
		}
		HAL_GPIO_WritePin(ledPort[bt],ledGPIO[bt],0);
		return 1;
	}
	return 0;
}

