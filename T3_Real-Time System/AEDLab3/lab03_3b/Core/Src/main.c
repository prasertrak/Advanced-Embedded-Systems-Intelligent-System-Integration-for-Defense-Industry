void uDelay(uint32_t us){
	uint32_t start;
	uint32_t finish = (start =__HAL_TIM_GetCounter(&htim2)) + us;
	if(start > finish){
		while(__HAL_TIM_GetCounter(&htim2)>start)
			osThreadYield(); // wait until it overruns
	}
	while(__HAL_TIM_GetCounter(&htim2)<finish)
		osThreadYield();
}

void LEDThread(void *argument)
{
  int i,tno=*(int *)argument;
  for(;;)
  {
	  for(i=0;i<100;i++){
		  pwm[tno]=i;
		  osDelay(delayTable[tno]);
	  }
	  for(i=100;i>0;i--){
		  pwm[tno]=i;
          osDelay(delayTable[tno]);
	  }
  }
}

void pwmThread(void *argument)
{
  int pOn,pOff,tno=*(int *)argument;
  for(;;)
  {
    pOn = pwm[tno]*2;
    pOff = 200-pOn;
    HAL_GPIO_WritePin(ledPort[tno],ledGPIO[tno],1);
    uDelay(pOn);
    HAL_GPIO_WritePin(ledPort[tno],ledGPIO[tno],0);
    uDelay(pOff);
  }
}
