/* USER CODE BEGIN 4 */
int getch(){
	int row,col;

	for(row=0;row<4;row++){
		HAL_GPIO_WritePin(GPIOC,keyRow[row],0);
		for(col=0;col<3;col++){
			if(HAL_GPIO_ReadPin(GPIOA,keyColumn[col])==0) break;
		}
		if(col<3)break; // key pressing detected
		HAL_GPIO_WritePin(GPIOC,keyRow[row],1);
	}
	if(row<4){
		while(HAL_GPIO_ReadPin(GPIOA,keyColumn[col])==0)  HAL_Delay(100);
		HAL_GPIO_WritePin(GPIOC,keyRow[row],1);
		return keyMap[row][col];
	}
	return -1;   //No key pressed
}
