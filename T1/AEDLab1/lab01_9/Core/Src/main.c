int isButtonPressed(int bt){
	// This version does not wait for button to depressed
	int x1=HAL_GPIO_ReadPin(buttonPort[bt&3],button[bt&3]);
	HAL_Delay(50);  //Delay for a bit to check for debouncing
	int x2=HAL_GPIO_ReadPin(buttonPort[bt&3],button[bt&3]);
	if((x1==x2)&&(x2==0)){
		return 1;
	}
	return 0;
}

void showLED(int speed,int direction){
	if(speed > 0){
		HAL_GPIO_WritePin(ledPort[0],ledGPIO[0],1);
		HAL_GPIO_WritePin(ledPort[1],ledGPIO[1],0);
	}else if(speed < 0){
		HAL_GPIO_WritePin(ledPort[0],ledGPIO[0],0);
		HAL_GPIO_WritePin(ledPort[1],ledGPIO[1],1);
	}else{
		HAL_GPIO_WritePin(ledPort[0],ledGPIO[0],1);
		HAL_GPIO_WritePin(ledPort[1],ledGPIO[1],1);
	}
	if(direction > 0){
		HAL_GPIO_WritePin(ledPort[3],ledGPIO[3],1);
		HAL_GPIO_WritePin(ledPort[2],ledGPIO[2],0);
	}else if(direction < 0){
		HAL_GPIO_WritePin(ledPort[3],ledGPIO[3],0);
		HAL_GPIO_WritePin(ledPort[2],ledGPIO[2],1);
	}else{
		HAL_GPIO_WritePin(ledPort[3],ledGPIO[3],0);
		HAL_GPIO_WritePin(ledPort[2],ledGPIO[2],0);
	}
}

void drive(int speed,int direction){
	//Valid value for speed is from -100 to 100
	//From backward to forward
	//Valid direction is from -100 to 100
	//From left to right

	int motorL = (speed + direction)*10;
	int motorR = (speed - direction)*10;
	if (motorL < -999) motorL = -999;
	if (motorL > 999)  motorL = 999;
	if (motorR < -999) motorR = -999;
	if (motorR > 999)  motorR = 999;

	if(motorL == 0){
		TIM4->CCR1 = 0;
		TIM4->CCR2 = 0;
	}else if(motorL > 0){
		TIM4->CCR2 = 0;
		TIM4->CCR1 = motorL;
	}else{
		TIM4->CCR1 = 0;
		TIM4->CCR2 = -motorL;
	}
	if(motorR == 0){
		TIM3->CCR1 = 0;
		TIM3->CCR2 = 0;
	}else if(motorR > 0){
		TIM3->CCR2 = 0;
		TIM3->CCR1 = motorR;
	}else{
	    TIM3->CCR1 = 0;
	    TIM3->CCR2 = -motorR;
	}
}

void setPWM(TIM_HandleTypeDef *timer, uint32_t channel, uint16_t pulse){
	HAL_TIM_PWM_Stop(timer,channel);
	TIM_OC_InitTypeDef sConfigOC;

	memset((void *)&sConfigOC,0,sizeof(sConfigOC));

	sConfigOC.OCMode = TIM_OCMODE_PWM1;
	sConfigOC.Pulse = pulse;
	sConfigOC.OCPolarity = TIM_OCPOLARITY_HIGH;
	sConfigOC.OCFastMode = TIM_OCFAST_DISABLE;
	HAL_TIM_PWM_ConfigChannel(timer, &sConfigOC, channel);
	HAL_TIM_PWM_Start(timer, channel);
}

